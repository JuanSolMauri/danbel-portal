CREATE TABLE IF NOT EXISTS families (
  code VARCHAR(10) NOT NULL PRIMARY KEY,
  name VARCHAR(120) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS products (
  code VARCHAR(20) NOT NULL PRIMARY KEY,
  family VARCHAR(10) NOT NULL,
  line_name VARCHAR(120) NULL,
  name VARCHAR(200) NOT NULL,
  ean VARCHAR(30) NULL,
  pvp DECIMAL(10,2) NULL,
  base_price DECIMAL(10,2) NOT NULL,
  image VARCHAR(200) NULL,
  tester TINYINT(1) NOT NULL DEFAULT 0,
  obsolete TINYINT(1) NOT NULL DEFAULT 0,
  prio TINYINT NOT NULL DEFAULT 0,
  KEY idx_products_family (family)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS discounts (
  customer_code INT NOT NULL,
  family VARCHAR(10) NOT NULL,
  dto DECIMAL(6,2) NOT NULL,
  PRIMARY KEY (customer_code, family)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  login VARCHAR(120) NOT NULL UNIQUE,
  role ENUM('admin','customer') NOT NULL,
  customer_code INT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS login_attempts (
  ip VARCHAR(45) NOT NULL,
  attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_attempts (ip, attempted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS customers (
  code INT NOT NULL PRIMARY KEY,
  fiscal_name VARCHAR(200) NULL,
  trade_name VARCHAR(100) NULL,
  address VARCHAR(100) NULL,
  postcode VARCHAR(15) NULL,
  city VARCHAR(100) NULL,
  province VARCHAR(50) NULL,
  nif VARCHAR(20) NULL,
  phone VARCHAR(25) NULL,
  email VARCHAR(100) NULL,
  account VARCHAR(40) NULL,
  vat DECIMAL(5,2) NULL,
  req DECIMAL(5,2) NULL,
  sales_rep VARCHAR(100) NULL,
  dto1 DECIMAL(5,2) NOT NULL DEFAULT 0,
  dto2 DECIMAL(5,2) NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS stock (
  code VARCHAR(20) NOT NULL PRIMARY KEY,
  qty INT NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS imports (
  id INT AUTO_INCREMENT PRIMARY KEY,
  imported_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  families INT NOT NULL,
  products INT NOT NULL,
  customers INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
